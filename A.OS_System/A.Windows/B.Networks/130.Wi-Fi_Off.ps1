$currentUser = [Security.Principal.WindowsIdentity]::GetCurrent()
$principal   = [Security.Principal.WindowsPrincipal]$currentUser
if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    Write-Host "  ERROR: This script requires administrator privileges." -ForegroundColor Red
    Write-Host "  Right-click the script and select 'Run as Administrator'." -ForegroundColor Yellow
    Write-Host ""
    Read-Host "Press Enter to exit..."
    exit 1
}

$adapters = Get-NetAdapter | Where-Object { $_.Name -match 'wi-?fi|wireless|wlan' -and $_.Status -eq 'Up' }

if ($adapters) {
    $adapters | Disable-NetAdapter -Confirm:$false
    Write-Host "  Wi-Fi adapter(s) disabled successfully." -ForegroundColor Green
} else {
    Write-Host "  No active Wi-Fi adapters found." -ForegroundColor Red
}

Write-Host ""
